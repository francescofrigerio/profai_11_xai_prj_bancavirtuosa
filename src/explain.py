    tensor_in = torch.tensor(norm_images, dtype=torch.float32).permute(0, 3, 1, 2).to(device)
        
    with torch.no_grad():
        logits = model(tensor_in)
        probs = F.softmax(logits, dim=1)
        return probs.cpu().numpy()

